public class Increment {
    public static void main(String[] args) {
        int i=56;
        System.out.println(i++);
        System.out.println(i);
        System.out.println(++i);
        System.out.println(i);
        int x=20;
        int y=x++;
        System.out.println(y);
        System.out.println(x);

        int a=7;
        int b= ++a*8;
        System.out.println(b);

        char ch='a';
        System.out.println(++ch);

    }
    
}
